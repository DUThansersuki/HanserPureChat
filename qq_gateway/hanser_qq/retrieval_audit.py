"""Local per-reply retrieval evidence; observes existing searches, never reruns them."""
from __future__ import annotations

import json
from contextvars import ContextVar
from datetime import datetime, timedelta, timezone


ACTIVE_AUDIT = ContextVar("qq_retrieval_audit", default=None)


class AuditedSearch:
    def __init__(self, original, name):
        self.original, self.name = original, name

    def __getattr__(self, name):
        return getattr(self.original, name)

    async def search(self, *args, **kwargs):
        audit = ACTIVE_AUDIT.get()
        try:
            result = await self.original.search(*args, **kwargs)
        except Exception as exc:
            if audit is not None:
                audit["searches"][self.name] = {"status": "failed", "error_type": type(exc).__name__}
            raise
        if audit is not None:
            audit["searches"][self.name] = {"status": "completed", "result": result.model_dump(mode="json")}
        return result


class AuditedContext:
    def __init__(self, original):
        self.original = original

    def __getattr__(self, name):
        return getattr(self.original, name)

    def build(self, **kwargs):
        context = self.original.build(**kwargs)
        audit = ACTIVE_AUDIT.get()
        if audit is not None:
            audit["selected"] = {key: [item.model_dump(mode="json") for item in kwargs.get(key, [])]
                                 for key in ("wiki_evidence", "style_examples", "memories")}
            audit["injected"] = {
                "style_ids": context.injected_style_ids,
                "source_ids": {key: context.block_sources.get(key, [])
                               for key in ("style_examples", "wiki_evidence", "memory")},
                "prompt_blocks": {key: context.blocks.get(key, "")
                                  for key in ("style_examples", "wiki_evidence", "memory")},
                "budget_drops": [item.model_dump(mode="json") for item in context.drop_ledger],
            }
            audit["conversation_contract"] = {
                "sources": context.block_sources.get("response_contract", []),
                "response_contract": context.blocks.get("response_contract", ""),
                "language_control": context.blocks.get("turn_language_control", ""),
            }
        return context


def attach_audit(agent):
    for name in ("style", "wiki", "memory"):
        attr = name + "_tool"
        original = getattr(agent, attr)
        if not isinstance(original, AuditedSearch):
            setattr(agent, attr, AuditedSearch(original, name))
    if not isinstance(agent.context_builder, AuditedContext):
        agent.context_builder = AuditedContext(agent.context_builder)


def write_audit(root, request, snapshot, audit):
    root.mkdir(parents=True, exist_ok=True)
    # reply_id is generated by ConversationStore, never a path supplied by QQ.
    path = root / f"{snapshot.reply_id}.json"
    if path.exists():
        return  # Replay must not replace the original retrieval with an empty observation.
    record = {
        "schema_version": "qq-retrieval-audit-v1",
        "recorded_at": datetime.now(timezone(timedelta(hours=8))).isoformat(timespec="seconds"),
        "request_id": request.request_id, "reply_id": snapshot.reply_id,
        "conversation_id": request.conversation_id, "user_id": request.user_id,
        "user_message": request.message,
        "semantic_reply": snapshot.semantic_text, "display_reply": snapshot.display_text,
        "retrieval_trace": snapshot.persona_trace.get("retrieval", {}),
        **audit,
        "product_override": {"authority": "user_request_2026_10_30", "scope": "qq",
                             "changes": ["short_bubbles", "natural_semantic_punctuation", "reduce_sentence_final_tilde"]},
        "note": "检索/注入记录不代表模型逐条采用；pending 原文保持 user_trial，未升级正式批准。",
    }
    content = json.dumps(record, ensure_ascii=False, indent=2) + "\n"
    temporary = path.with_suffix(".tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(path)
    latest = root / "latest.tmp"
    latest.write_text(content, encoding="utf-8")
    latest.replace(root / "latest.json")
